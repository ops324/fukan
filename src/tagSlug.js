// タグ名 → ファイル名/URL に使える形への変換。依存ゼロ・I/O なしの葉モジュール。
//
// 「外部入力 → 出力」の境界で必ず通すエスケープ経路の一つ（esc() / mdToHtml() / xmlEsc と同格）。
// タグは writer(LLM) が自由に書く文字列なので、そのままファイル名にすると
// 'AR/VR' が dist/tags/AR/VR.html と解釈されて ENOENT で render 全体が落ちる（2026-07-26 の事故）。
//
// 置換対象は「ファイルパスとして壊れる文字」だけに絞る。日本語・空白・'&'・'+'・'-'・'.'・
// '#'・'%' は、生 UTF-8 のファイル名＋リンク側 encodeURIComponent で従来どおり成立するため触らない
// （'Physical AI' / 'M&A' / 'LGBTQ+' / 'GLP-1' / 'GPT-5.6' はすべて現行 URL のまま）。
// これにより既存 1757 種のタグはすべて不動点になり、公開済み URL は 1 つも変わらない。
//
// '#' '%' を残すのは意図的。URL では特別な意味を持つが href 側で必ず '%23' '%25' に
// エンコードされるため生では現れない。一方これらを '-' に潰すと、取り込み時の正規化
// （store.js）を通じて 'C#' が 'C-' として保存され、読者に見えるタグ名が劣化する。
const UNSAFE = /[\\/:*?"<>|]/g;

// 制御文字。ソースに生のバイトを埋めないよう文字列から組み立てる。
const CONTROL = new RegExp('[\\u0000-\\u001F\\u007F]', 'g');

export function tagSlug(tag) {
  const s = String(tag ?? '')
    .trim()                    // 前後の空白はファイル名では見えず事故のもと
    .replace(UNSAFE, '-')      // パス区切り・予約文字
    .replace(CONTROL, '-')
    .replace(/^\.+|\.+$/g, '') // 先頭 '.' は隠しファイル、'..' や末尾 '.' は親ディレクトリ参照
    .trim();
  return s || '_';
}
